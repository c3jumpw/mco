// Invoice editing: draft lines (direct writes, never `amount`), notes, and the mark-paid and void sheets.
import { useEffect, useState } from 'react';
import { supabase, errText } from '../../../lib/supabase';
import { q } from '../../../lib/hooks';
import { money } from '../../../lib/util';
import type { Invoice, InvoiceLine } from '../../../lib/types';
import { Button, Card, CardHeader, EmptyState, Field, IconButton, Input, Notice, Sheet, Textarea, useConfirm, useToast } from '../../../ui';
import { num, parseNum, round2 } from './money-common';

export type LineMode = 'line' | 'credit';
export interface LineTarget { mode: LineMode; line?: InvoiceLine }

const KIND_NOTE: Partial<Record<InvoiceLine['kind'], string>> = {
  hours: 'This line comes from approved timesheets. Changing it here doesn’t change the hours on them.',
  prepay: 'This is a prepayment for scheduled hours. The difference is settled on a later invoice from the hours actually worked.',
  setup_fee: 'This is the placement’s one-time setup fee.',
  adjustment: 'This line settles the difference between prepaid and worked hours, or is a credit.',
};

const isCredit = (l: InvoiceLine) => Number(l.quantity) === -1 && !l.placement_id;

export function LineSheet({ target, invoice, nextSort, onClose, onSaved }:
  { target: LineTarget | null; invoice: Invoice; nextSort: number; onClose: () => void; onSaved: () => void }) {
  const toast = useToast();
  const [description, setDescription] = useState('');
  const [qty, setQty] = useState('1');
  const [price, setPrice] = useState('');
  const [err, setErr] = useState('');
  const [busy, setBusy] = useState(false);
  const cur = invoice.currency;

  useEffect(() => {
    if (!target) return;
    const l = target.line;
    setDescription(l?.description || '');
    setQty(l ? String(Number(l.quantity)) : '1');
    setPrice(l ? String(Number(l.unit_price)) : '');
    setErr('');
  }, [target]);
  if (!target) return null;
  const credit = target.mode === 'credit';
  const editing = !!target.line;

  const q1 = credit ? -1 : parseNum(qty);
  const p1 = parseNum(price);
  const preview = Number.isFinite(q1) && Number.isFinite(p1) ? round2(q1 * p1) : null;

  async function save() {
    setErr('');
    const desc = description.trim();
    if (!desc) return setErr(credit ? 'Say what the credit is for.' : 'Describe the line.');
    if (!credit && (!Number.isFinite(q1) || q1 === 0 || Math.abs(q1) >= 1e8)) return setErr('Enter a quantity, for example 1 or 2.5. Use a negative number to take something off.');
    if (!Number.isFinite(p1) || p1 < 0 || p1 >= 1e8) return setErr(credit ? 'Enter the credit amount, for example 50.' : 'Enter a price of 0 or more.');
    if (credit && p1 === 0) return setErr('Enter the credit amount, for example 50.');
    setBusy(true);
    try {
      // `amount` is generated by the database (quantity × unit price). Never send it.
      const fields = { description: desc.slice(0, 500), quantity: round2(q1), unit_price: round2(p1) };
      if (editing) await q(supabase.from('ramp_invoice_lines').update(fields).eq('id', target!.line!.id));
      else await q(supabase.from('ramp_invoice_lines').insert({ ...fields, invoice_id: invoice.id, kind: credit ? 'adjustment' : 'other', sort: nextSort }));
      toast(editing ? 'Line updated.' : credit ? 'Credit added.' : 'Line added.');
      onSaved();
      onClose();
    } catch (e) {
      setErr(errText(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <Sheet open onClose={onClose} title={editing ? 'Edit line' : credit ? 'Add a credit' : 'Add a line'}
      subtitle={credit ? 'A credit takes an amount off this invoice, for example for a missed day or a goodwill discount.' : 'For anything that isn’t hours, like a tool subscription or an extra service.'}
      footer={<><Button onClick={onClose}>Cancel</Button><Button variant="primary" icon="check" loading={busy} onClick={save}>{editing ? 'Save line' : credit ? 'Add credit' : 'Add line'}</Button></>}>
      {editing && target.line && KIND_NOTE[target.line.kind] && !isCredit(target.line) && <Notice>{KIND_NOTE[target.line.kind]}</Notice>}
      <Field label="Description" required hint="The client sees this on the invoice.">
        <Input value={description} onChange={(e) => setDescription(e.target.value)} maxLength={500}
          placeholder={credit ? 'Credit: office closed Nov 11' : 'Software license, November'} />
      </Field>
      {credit ? (
        <Field label={`Credit amount (${cur})`} required>
          <Input inputMode="decimal" value={price} onChange={(e) => setPrice(e.target.value)} placeholder="50.00" />
        </Field>
      ) : (
        <div className="grid grid-cols-2 gap-3">
          <Field label="Quantity" required>
            <Input inputMode="decimal" value={qty} onChange={(e) => setQty(e.target.value)} placeholder="1" />
          </Field>
          <Field label={`Unit price (${cur})`} required>
            <Input inputMode="decimal" value={price} onChange={(e) => setPrice(e.target.value)} placeholder="0.00" />
          </Field>
        </div>
      )}
      {preview !== null && (
        <p className="flex justify-between text-[15px] rounded-xl bg-bg px-4 py-3">
          <span className="text-muted">Line amount</span>
          <span className="font-semibold tabular-nums">{money(preview, cur)}</span>
        </p>
      )}
      {err && <Notice tone="bad" icon="alert">{err}</Notice>}
    </Sheet>
  );
}

/** The draft's lines with edit and remove, plus add buttons. */
export function LinesEditor({ invoice, lines, onEdit, onChanged }:
  { invoice: Invoice; lines: InvoiceLine[]; onEdit: (t: LineTarget) => void; onChanged: () => void }) {
  const toast = useToast();
  const { confirm, dialog } = useConfirm();
  const [busy, setBusy] = useState<string | null>(null);
  const cur = invoice.currency;

  async function remove(l: InvoiceLine) {
    const extra = l.kind === 'hours' ? ' Its hours go back to unbilled, so they can go on another invoice.'
      : l.kind === 'setup_fee' ? ' The setup fee goes back to unbilled.'
        : l.kind === 'prepay' ? ' Those weeks won’t be prepaid on this invoice.' : '';
    const ok = await confirm({ title: 'Remove this line?', body: `${l.description || 'Line'} · ${money(l.amount, cur)}.${extra}`, action: 'Remove line', danger: true });
    if (!ok) return;
    setBusy(l.id);
    try {
      await q(supabase.from('ramp_invoice_lines').delete().eq('id', l.id));
      if (l.kind === 'setup_fee' && l.placement_id) {
        await q(supabase.from('ramp_placements').update({ setup_fee_status: 'unbilled' }).eq('id', l.placement_id).eq('setup_fee_status', 'invoiced'));
      }
      toast('Line removed.');
    } catch (e) {
      toast(errText(e), 'bad');
    } finally {
      setBusy(null);
      onChanged();
    }
  }

  return (
    <Card>
      <CardHeader title="Edit lines" subtitle="Drafts can change. Once you issue the invoice, the lines lock."
        action={<div className="flex flex-wrap gap-2">
          <Button size="sm" icon="plus" onClick={() => onEdit({ mode: 'line' })}>Add a line</Button>
          <Button size="sm" icon="plus" onClick={() => onEdit({ mode: 'credit' })}>Add a credit</Button>
        </div>} />
      {lines.length === 0 ? (
        <EmptyState icon="list" title="No lines" body="Add a line, or discard this draft and create a new one for a different period." />
      ) : (
        <ul className="mt-4 border-t border-line-2">
          {lines.map((l) => (
            <li key={l.id} className="py-2 border-b border-line-2">
              <p className="text-[15px] leading-snug pt-1">{l.description || 'Line'}</p>
              <div className="flex items-center gap-1">
                <span className="flex-1 text-sm text-muted tabular-nums">{num(l.quantity)} × {money(l.unit_price, cur)}</span>
                <span className="text-[15px] font-semibold tabular-nums whitespace-nowrap mr-1">{money(l.amount, cur)}</span>
                <IconButton icon="pen" label={`Edit ${l.description || 'line'}`} disabled={busy === l.id}
                  onClick={() => onEdit({ mode: isCredit(l) ? 'credit' : 'line', line: l })} />
                <IconButton icon="trash" label={`Remove ${l.description || 'line'}`} disabled={busy === l.id} onClick={() => remove(l)} />
              </div>
            </li>
          ))}
        </ul>
      )}
      <NotesEditor invoice={invoice} onSaved={onChanged} />
      {dialog}
    </Card>
  );
}

function NotesEditor({ invoice, onSaved }: { invoice: Invoice; onSaved: () => void }) {
  const toast = useToast();
  const [notes, setNotes] = useState(invoice.notes || '');
  const [busy, setBusy] = useState(false);
  useEffect(() => { setNotes(invoice.notes || ''); }, [invoice.notes]);
  const dirty = notes.trim() !== (invoice.notes || '').trim();
  async function save() {
    setBusy(true);
    try {
      await q(supabase.from('ramp_invoices').update({ notes: notes.trim().slice(0, 2000) }).eq('id', invoice.id));
      toast('Notes saved.');
      onSaved();
    } catch (e) {
      toast(errText(e), 'bad');
    } finally {
      setBusy(false);
    }
  }
  return (
    <div className="mt-5 flex flex-col gap-2">
      <Field label="Notes on the invoice" hint="Optional. Printed at the bottom, for example payment instructions or a thank-you.">
        <Textarea rows={2} value={notes} onChange={(e) => setNotes(e.target.value)} maxLength={2000} placeholder="Please pay by bank transfer to …" />
      </Field>
      {dirty && <Button size="sm" variant="primary" icon="check" loading={busy} onClick={save} className="self-start">Save notes</Button>}
    </div>
  );
}

// ───────── status changes ─────────

export function MarkPaidSheet({ open, invoice, clientName, onClose, onDone }:
  { open: boolean; invoice: Invoice; clientName: string; onClose: () => void; onDone: () => void }) {
  const toast = useToast();
  const [note, setNote] = useState('');
  const [busy, setBusy] = useState(false);
  useEffect(() => { if (open) setNote(''); }, [open]);
  async function submit() {
    setBusy(true);
    try {
      await q(supabase.rpc('ramp_invoice_set_status', { p_invoice: invoice.id, p_status: 'paid', p_note: note.trim() }));
      toast(`${invoice.number} marked paid.`);
      onClose();
      onDone();
    } catch (e) {
      toast(errText(e), 'bad');
    } finally {
      setBusy(false);
    }
  }
  return (
    <Sheet open={open} onClose={onClose} title={`Mark ${invoice.number} as paid?`}
      footer={<><Button onClick={onClose}>Cancel</Button><Button variant="success" icon="check" loading={busy} onClick={submit}>Mark as paid</Button></>}>
      <p className="text-[15px] text-ink-2 leading-relaxed">
        Records that {clientName} paid {money(invoice.total, invoice.currency)} today. Hours on this invoice can then go on a payout.
      </p>
      <Field label="How was it paid?" hint="Optional, for your records. For example a transfer number.">
        <Input value={note} onChange={(e) => setNote(e.target.value)} maxLength={500} placeholder="Wise transfer #123" />
      </Field>
      {invoice.stripe_invoice_id && (
        <Notice tone="warn">
          This invoice was sent through Stripe. If the client paid another way, mark it paid in Stripe too
          (Invoice › Change status › Mark as paid) so Stripe stops sending reminders.
        </Notice>
      )}
    </Sheet>
  );
}

export function VoidSheet({ open, invoice, clientName, onClose, onDone }:
  { open: boolean; invoice: Invoice; clientName: string; onClose: () => void; onDone: () => void }) {
  const toast = useToast();
  const [reason, setReason] = useState('');
  const [busy, setBusy] = useState(false);
  useEffect(() => { if (open) setReason(''); }, [open]);
  async function submit() {
    setBusy(true);
    try {
      await q(supabase.rpc('ramp_invoice_set_status', { p_invoice: invoice.id, p_status: 'void', p_note: reason.trim() ? `Voided: ${reason.trim()}` : '' }));
      toast(`${invoice.number} voided.`);
      onClose();
      onDone();
    } catch (e) {
      toast(errText(e), 'bad');
    } finally {
      setBusy(false);
    }
  }
  return (
    <Sheet open={open} onClose={onClose} title={`Void ${invoice.number}?`}
      footer={<><Button onClick={onClose}>Cancel</Button><Button variant="danger" icon="x" loading={busy} onClick={submit}>Void invoice</Button></>}>
      <p className="text-[15px] text-ink-2 leading-relaxed">
        Cancels this {money(invoice.total, invoice.currency)} invoice to {clientName}. Its hours, prepayments and setup fees go back to unbilled,
        so you can put them on a new invoice. {clientName} can still see it in RAMP, marked void. This can’t be undone.
      </p>
      <Field label="Reason" hint="Optional. It’s added to the invoice notes, which the client can see.">
        <Textarea rows={2} value={reason} onChange={(e) => setReason(e.target.value)} maxLength={300} placeholder="Wrong hours for Nov 10, replaced by a new invoice" />
      </Field>
      {invoice.stripe_invoice_id && (
        <Notice tone="warn" icon="alert">
          This invoice was sent through Stripe. Void it in Stripe as well, or the client can still pay the Stripe link.
        </Notice>
      )}
    </Sheet>
  );
}
