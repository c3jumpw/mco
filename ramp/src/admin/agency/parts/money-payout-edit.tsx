// Payout editing: bonus and adjustment lines (direct writes, never `amount`) and the "mark as sent" sheet.
import { useEffect, useState } from 'react';
import { supabase, errText } from '../../../lib/supabase';
import { q } from '../../../lib/hooks';
import { money, plural } from '../../../lib/util';
import type { Payout, PayoutLine } from '../../../lib/types';
import { Button, Checkbox, Field, Input, Notice, Pills, Select, Sheet, useToast } from '../../../ui';
import { parseNum, round2 } from './money-common';

export interface PayoutLineTarget { line?: PayoutLine; memberId?: string }

export function PayoutLineSheet({ target, payout, assistants, nextSort, onClose, onSaved }: {
  target: PayoutLineTarget | null; payout: Payout; assistants: { id: string; name: string }[]; nextSort: number;
  onClose: () => void; onSaved: () => void;
}) {
  const toast = useToast();
  const [memberId, setMemberId] = useState('');
  const [kind, setKind] = useState<'bonus' | 'adjustment'>('bonus');
  const [description, setDescription] = useState('');
  const [amount, setAmount] = useState('');
  const [deduct, setDeduct] = useState(false);
  const [err, setErr] = useState('');
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (!target) return;
    const l = target.line;
    setMemberId(l?.member_id || target.memberId || '');
    setKind(l?.kind === 'adjustment' ? 'adjustment' : 'bonus');
    setDescription(l?.description || '');
    setAmount(l ? String(Math.abs(round2(Number(l.quantity) * Number(l.rate)))) : '');
    setDeduct(!!l && Number(l.quantity) * Number(l.rate) < 0);
    setErr('');
  }, [target]);
  if (!target) return null;
  const editing = !!target.line;
  const cur = payout.currency;
  const n = parseNum(amount);
  const signed = Number.isFinite(n) ? (kind === 'adjustment' && deduct ? -n : n) : null;

  async function save() {
    setErr('');
    if (!memberId) return setErr('Pick who this is for.');
    if (!description.trim()) return setErr(kind === 'bonus' ? 'Say what the bonus is for.' : 'Say what the adjustment is for.');
    if (!Number.isFinite(n) || n <= 0 || n >= 1e8) return setErr('Enter an amount greater than 0.');
    setBusy(true);
    try {
      // quantity × rate makes the amount (generated by the database; never send `amount`). A deduction is quantity −1.
      const fields = { member_id: memberId, kind, description: description.trim().slice(0, 500), quantity: kind === 'adjustment' && deduct ? -1 : 1, rate: round2(n) };
      if (editing) await q(supabase.from('ramp_payout_lines').update(fields).eq('id', target!.line!.id));
      else await q(supabase.from('ramp_payout_lines').insert({ ...fields, payout_id: payout.id, placement_id: null, sort: nextSort }));
      toast(editing ? 'Line updated.' : kind === 'bonus' ? 'Bonus added.' : 'Adjustment added.');
      onSaved();
      onClose();
    } catch (e) {
      setErr(errText(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <Sheet open onClose={onClose} title={editing ? 'Edit line' : 'Add a bonus or adjustment'}
      subtitle="It’s added to this payout. The team member sees it on their My work page."
      footer={<><Button onClick={onClose}>Cancel</Button><Button variant="primary" icon="check" loading={busy} onClick={save}>{editing ? 'Save line' : 'Add to payout'}</Button></>}>
      <Field label="Team member" required>
        <Select value={memberId} onChange={(e) => setMemberId(e.target.value)}>
          <option value="">Pick a team member…</option>
          {assistants.map((a) => <option key={a.id} value={a.id}>{a.name}</option>)}
        </Select>
      </Field>
      <fieldset className="flex flex-col gap-2">
        <legend className="text-[13px] font-semibold text-ink-2 mb-1.5">Type</legend>
        <Pills label="Type" size="sm" value={kind} onChange={setKind} options={[{ value: 'bonus', label: 'Bonus' }, { value: 'adjustment', label: 'Adjustment' }]} />
      </fieldset>
      <Field label="Description" required hint="The team member sees this.">
        <Input value={description} onChange={(e) => setDescription(e.target.value)} maxLength={500}
          placeholder={kind === 'bonus' ? 'Performance bonus, October' : 'Correction for Nov 4 hours'} />
      </Field>
      <Field label={`Amount (${cur})`} required>
        <Input inputMode="decimal" value={amount} onChange={(e) => setAmount(e.target.value)} placeholder="25.00" />
      </Field>
      {kind === 'adjustment' && (
        <Checkbox checked={deduct} onChange={setDeduct} label="Take this amount off" hint="For example, to correct an overpayment. Leave unticked to add it." />
      )}
      {signed !== null && signed !== 0 && (
        <p className="flex justify-between text-[15px] rounded-xl bg-bg px-4 py-3">
          <span className="text-muted">On this payout</span>
          <span className="font-semibold tabular-nums">{money(signed, cur)}</span>
        </p>
      )}
      {err && <Notice tone="bad" icon="alert">{err}</Notice>}
    </Sheet>
  );
}

export function MarkSentSheet({ open, payout, people, onClose, onDone }:
  { open: boolean; payout: Payout; people: number; onClose: () => void; onDone: () => void }) {
  const toast = useToast();
  const [reference, setReference] = useState('');
  const [sure, setSure] = useState(false);
  const [busy, setBusy] = useState(false);
  useEffect(() => { if (open) { setReference(''); setSure(false); } }, [open]);
  async function submit() {
    setBusy(true);
    try {
      await q(supabase.rpc('ramp_payout_set_status', { p_payout: payout.id, p_status: 'sent', p_reference: reference.trim() }));
      toast('Payout marked as sent.');
      onClose();
      onDone();
    } catch (e) {
      toast(errText(e), 'bad');
    } finally {
      setBusy(false);
    }
  }
  return (
    <Sheet open={open} onClose={onClose} title="Mark this payout as sent?"
      footer={<><Button onClick={onClose}>Cancel</Button><Button variant="success" icon="check" loading={busy} disabled={!sure} onClick={submit}>Mark as sent</Button></>}>
      <p className="text-[15px] text-ink-2 leading-relaxed">
        Records that {money(payout.total, payout.currency)} went to {plural(people, 'team member')}. The payout locks, and each team member sees it as paid in My work.
      </p>
      <Field label="Reference" hint="Optional, for your records. For example the Wise batch number.">
        <Input value={reference} onChange={(e) => setReference(e.target.value)} maxLength={200} placeholder="Wise batch #12345" />
      </Field>
      <Checkbox checked={sure} onChange={setSure} label="The money has been sent" hint="In Wise, or by bank transfer for anyone paid that way." />
    </Sheet>
  );
}
